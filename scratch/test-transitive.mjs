import fs from "fs/promises";
import path from "path";
import { fileURLToPath } from "url";
import { registerAnalysisTools } from "../build/tools/analysis.js";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const workspaceRoot = path.join(__dirname, "..");
const tempDir = path.join(workspaceRoot, "scratch", "temp-test-projects");
const originalIndexPat = path.join(workspaceRoot, "symbol_index.json");
const backupIndexPat = path.join(workspaceRoot, "symbol_index.json.bak");

async function setupMockProjects() {
  console.log("Creating temporary mock projects directory...");
  await fs.mkdir(tempDir, { recursive: true });

  // 1. Setup npm-proj-a with a classic package-lock.json (v1) nested structure
  // express -> accepts -> mime-types
  const npmProjA = path.join(tempDir, "npm-proj-a");
  await fs.mkdir(npmProjA, { recursive: true });
  await fs.writeFile(
    path.join(npmProjA, "package.json"),
    JSON.stringify({
      name: "npm-proj-a",
      version: "1.0.0",
      dependencies: {
        express: "^4.18.2"
      }
    }, null, 2)
  );

  await fs.writeFile(
    path.join(npmProjA, "package-lock.json"),
    JSON.stringify({
      name: "npm-proj-a",
      version: "1.0.0",
      lockfileVersion: 1,
      requires: true,
      dependencies: {
        express: {
          version: "4.18.2",
          dependencies: {
            accepts: {
              version: "1.3.8",
              dependencies: {
                "mime-types": {
                  version: "2.1.35"
                }
              }
            }
          }
        }
      }
    }, null, 2)
  );

  // 2. Setup npm-proj-b with a conflict version of mime-types (e.g. 1.0.0, which doesn't intersect 2.1.35)
  // mime-types -> mime-db
  const npmProjB = path.join(tempDir, "npm-proj-b");
  await fs.mkdir(npmProjB, { recursive: true });
  await fs.writeFile(
    path.join(npmProjB, "package.json"),
    JSON.stringify({
      name: "npm-proj-b",
      version: "1.0.0",
      dependencies: {
        "mime-types": "^1.0.0"
      }
    }, null, 2)
  );

  await fs.writeFile(
    path.join(npmProjB, "package-lock.json"),
    JSON.stringify({
      name: "npm-proj-b",
      version: "1.0.0",
      lockfileVersion: 2,
      requires: true,
      packages: {
        "": {
          name: "npm-proj-b",
          version: "1.0.0",
          dependencies: {
            "mime-types": "^1.0.0"
          }
        },
        "node_modules/mime-types": {
          version: "1.0.0",
          dependencies: {
            "mime-db": "1.30.0"
          }
        },
        "node_modules/mime-db": {
          version: "1.30.0"
        }
      }
    }, null, 2)
  );

  // 3. Setup cargo-proj-a (Rust workspace project)
  // my-rust-app -> serde -> serde_derive
  const cargoProjA = path.join(tempDir, "cargo-proj-a");
  await fs.mkdir(cargoProjA, { recursive: true });
  await fs.writeFile(
    path.join(cargoProjA, "Cargo.toml"),
    `[package]
name = "cargo-proj-a"
version = "0.1.0"

[dependencies]
serde = "1.0.190"
`
  );

  await fs.writeFile(
    path.join(cargoProjA, "Cargo.lock"),
    `# This file is automatically @generated by Cargo.
# It is not intended for manual editing.
version = 3

[[package]]
name = "cargo-proj-a"
version = "0.1.0"
dependencies = [
 "serde",
]

[[package]]
name = "serde"
version = "1.0.190"
dependencies = [
 "serde_derive",
]

[[package]]
name = "serde_derive"
version = "1.0.190"
`
  );

  // 4. Setup fallback-proj without lockfiles
  const fallbackProj = path.join(tempDir, "fallback-proj");
  await fs.mkdir(fallbackProj, { recursive: true });
  await fs.writeFile(
    path.join(fallbackProj, "package.json"),
    JSON.stringify({
      name: "fallback-proj",
      version: "1.0.0",
      dependencies: {
        "lodash": "^4.17.21"
      }
    }, null, 2)
  );

  console.log("Mock projects structured successfully.");
}

async function writeMockIndex() {
  console.log("Backing up symbol_index.json...");
  try {
    const originalContent = await fs.readFile(originalIndexPat, "utf-8");
    await fs.writeFile(backupIndexPat, originalContent);
  } catch (err) {
    console.warn("No existing symbol_index.json found to back up.");
  }

  console.log("Writing temporary test symbol_index.json...");
  const mockIndex = {
    "npm-proj-a": {
      path: path.join(tempDir, "npm-proj-a"),
      symbols: [],
      lastIndexed: new Date().toISOString()
    },
    "npm-proj-b": {
      path: path.join(tempDir, "npm-proj-b"),
      symbols: [],
      lastIndexed: new Date().toISOString()
    },
    "cargo-proj-a": {
      path: path.join(tempDir, "cargo-proj-a"),
      symbols: [],
      lastIndexed: new Date().toISOString()
    },
    "fallback-proj": {
      path: path.join(tempDir, "fallback-proj"),
      symbols: [],
      lastIndexed: new Date().toISOString()
    }
  };

  await fs.writeFile(originalIndexPat, JSON.stringify(mockIndex, null, 2));
}

async function restoreIndexAndCleanup() {
  console.log("Restoring symbol_index.json backup...");
  try {
    const backupContent = await fs.readFile(backupIndexPat, "utf-8");
    await fs.writeFile(originalIndexPat, backupContent);
    await fs.unlink(backupIndexPat);
  } catch (err) {
    console.warn("Could not restore original symbol_index.json.");
  }

  console.log("Deleting temporary mock projects...");
  await fs.rm(tempDir, { recursive: true, force: true });
  console.log("Cleanup done.");
}

async function runTests() {
  console.log("=== Running Transitive Lockfile Auditing Integration Tests ===");

  const ctx = {
    axiosInstance: {},
    rateLimiterConfig: { max_dollars: 10.00, warn_at_percent: 80, max_requests_per_minute: 20 },
    sessionUsage: { prompt_tokens: 0, completion_tokens: 0, cost: 0.0 },
    circuitBreakerMap: new Map(),
    tokenBucketMap: new Map(),
    pricingCache: {}
  };

  const { handlers } = registerAnalysisTools(ctx);
  const handleDependencyGraph = handlers.dependency_graph;

  // TEST 1: Transitive lockfile resolution for NPM and Cargo
  console.log("\n--- TEST 1: Transitive Lockfile Parsing ---");
  const res1 = await handleDependencyGraph({
    transitive: true,
    check_conflicts: false
  });

  if (res1.isError) {
    console.error("❌ TEST 1 Failed with error:", res1.content[0].text);
    process.exit(1);
  }

  const text1 = res1.content[0].text;
  console.log(text1);

  // Assertions for TEST 1:
  // - Should report 'npm (lockfile)' and 'cargo (lockfile)' and 'npm' for fallback
  // - Scanned unique package count should include transitive deps: express, accepts, mime-types, mime-db, serde, serde_derive
  if (!text1.includes("npm (lockfile)") || !text1.includes("cargo (lockfile)")) {
    console.error("❌ TEST 1 Failed: Resolver types npm (lockfile) or cargo (lockfile) missing in summary table.");
    process.exit(1);
  }
  if (!text1.includes("Scanned 8 unique package definitions")) {
    console.error("❌ TEST 1 Failed: Expected scanned unique packages count (8) is incorrect or missing.");
    process.exit(1);
  }
  console.log("✅ TEST 1 Passed: Lockfiles successfully parsed and structured!");

  // TEST 2: Targeted query (focus_package) on NPM chain
  console.log("\n--- TEST 2: Targeted Package Trace (NPM) ---");
  const res2 = await handleDependencyGraph({
    transitive: true,
    focus_package: "mime-types"
  });

  if (res2.isError) {
    console.error("❌ TEST 2 Failed with error:", res2.content[0].text);
    process.exit(1);
  }

  const text2 = res2.content[0].text;
  console.log(text2);

  // Assertions for TEST 2:
  // - Path should trace back: npm-proj-a ➔ express ➔ accepts ➔ mime-types
  if (!text2.includes("npm-proj-a") || !text2.includes("express") || !text2.includes("accepts") || !text2.includes("mime-types")) {
    console.error("❌ TEST 2 Failed: Path trace did not correctly map npm-proj-a -> express -> accepts -> mime-types");
    process.exit(1);
  }
  console.log("✅ TEST 2 Passed: Targeted package trace successfully resolved deep chains!");

  // TEST 3: Targeted query (focus_package) on Cargo chain
  console.log("\n--- TEST 3: Targeted Package Trace (Cargo) ---");
  const res3 = await handleDependencyGraph({
    transitive: true,
    focus_package: "serde_derive"
  });

  const text3 = res3.content[0].text;
  console.log(text3);

  // Assertions for TEST 3:
  // - Path should trace back: cargo-proj-a ➔ serde ➔ serde_derive
  if (!text3.includes("cargo-proj-a") || !text3.includes("serde") || !text3.includes("serde_derive")) {
    console.error("❌ TEST 3 Failed: Path trace did not correctly map cargo-proj-a -> serde -> serde_derive");
    process.exit(1);
  }
  console.log("✅ TEST 3 Passed: Cargo dependency path trace resolved successfully!");

  // TEST 4: Semver Conflict Detection
  console.log("\n--- TEST 4: Semver Conflict Detection ---");
  const res4 = await handleDependencyGraph({
    transitive: true,
    check_conflicts: true
  });

  const text4 = res4.content[0].text;
  console.log(text4);

  // Assertions for TEST 4:
  // - Should report semver conflicts for mime-types (1.0.0 vs 2.1.35, which are non-intersecting)
  if (!text4.includes("Transitive Semver Conflicts") || !text4.includes("mime-types") || !text4.includes("1.0.0") || !text4.includes("2.1.35")) {
    console.error("❌ TEST 4 Failed: Expected non-intersecting mime-types conflict was not flagged!");
    process.exit(1);
  }
  console.log("✅ TEST 4 Passed: Transitive semver conflict detected successfully!");

  // TEST 5: Fallback handling for missing lockfiles
  console.log("\n--- TEST 5: Missing Lockfile Fallback ---");
  // fallback-proj has package.json but no package-lock.json
  const res5 = await handleDependencyGraph({
    transitive: true,
    repos: ["fallback-proj"]
  });

  const text5 = res5.content[0].text;
  console.log(text5);

  // Assertions for TEST 5:
  // - Should fall back to direct manifest parse, warning about missing lockfile, and showing 1 direct package.
  if (!text5.includes("Could not locate or parse lockfile in repository") || !text5.includes("fallback-proj | npm | 1 (direct)")) {
    console.error("❌ TEST 5 Failed: Did not gracefully report missing lockfile warning or fallback to direct manifest.");
    process.exit(1);
  }
  console.log("✅ TEST 5 Passed: Missing lockfile warning and manifest fallback successfully completed!");

  console.log("\n🎉 All Transitive Lockfile Auditing Integration Tests Passed!");
}

async function main() {
  try {
    await setupMockProjects();
    await writeMockIndex();
    await runTests();
  } finally {
    await restoreIndexAndCleanup();
  }
}

main().catch(err => {
  console.error("❌ Execution error:", err);
  process.exit(1);
});
